package fingerprintmodel;

import ai.djl.Model;
import ai.djl.inference.Predictor;
import ai.djl.ndarray.NDList;
import ai.djl.ndarray.NDManager;
import ai.djl.ndarray.types.Shape;
import ai.djl.translate.TranslateException;
import ai.djl.translate.Translator;
import ai.djl.translate.TranslatorContext;

import java.nio.file.Path;

/**
 * Provides services for generating fingerprint embeddings and comparing
 * fingerprints using a trained deep learning model.
 *
 * <p>The service loads a fingerprint encoder model using DJL. It accepts normalized
 * 256 x 256 grayscale pixel arrays and passes them to the model to generate
 * numerical fingerprint embeddings.
 *
 * <p>Two embeddings can be compared using Euclidean distance. A smaller distance indicates
 * that the embeddings are closer in the model's feature space.
 */
public class FingerprintEncoderService implements AutoCloseable {
    private static final float THRESHOLD = 0.362583f;

    private final Model model;
    private final Predictor<NDList, float[]> predictor;
    private final NDManager manager;

    /**
     * Creates a fingerprint encoder service and loads the trained model
     * from the specified path.
     *
     * @param modelPath the filesystem path to the trained model
     * @throws Exception if the manager or model cannot be initialized or loaded
     */
    public FingerprintEncoderService(Path modelPath) throws Exception {
        manager = NDManager.newBaseManager();

        model = Model.newInstance("fingerprint-encoder", "PyTorch");
        model.load(modelPath);

        Translator<NDList, float[]> translator =
            new Translator<>() {
                /**
                 * Prepares the input before model inference.
                 *
                 * @param ctx the toolkit for creating the input NDArray
                 * @param input the input object
                 * @return the unchanged input arrays
                 */
                @Override
                public NDList processInput(
                        TranslatorContext ctx, NDList input) {
                    return input;
                }

                /**
                 * Converts the model output into a Java float array.
                 *
                 * @param ctx the toolkit used for post-processing
                 * @param output the output NDList after inference, usually immutable in engines like
                 *     PyTorch. @see <a href="https://github.com/deepjavalibrary/djl/issues/1774">Issue 1774</a>
                 * @return the first output array converted to float values
                 */
                @Override
                public float[] processOutput(
                        TranslatorContext ctx, NDList output) {
                    return output.getFirst().toFloatArray();
                }
            };

        predictor = model.newPredictor(translator);
    }

    /**
     * Generates a numerical embedding for a fingerprint image.
     *
     * @param pixels the normalized grayscale pixel values of the image
     * @return the fingerprint embedding generated by the model
     * @throws IllegalArgumentException if the input image dimensions are
     * invalid (not 256 x 256)
     * @throws TranslateException if model inference fails
     */
    public float[] embed(float[] pixels) throws TranslateException {
        final int width = 256;
        final int height = 256;

        if (pixels.length != width * height) {
            throw new IllegalArgumentException(
                    "Expected exactly " + (width * height) +
                            " grayscale pixels."
            );
        }

        // Convert Java float array into DJL numerical array.
        var image = manager.create(pixels, new Shape(1, width, height));
        return predictor.predict(new NDList(image));
    }

    /**
     * Calculates the Euclidean distance between two fingerprint embeddings
     * generated from the supplied images.
     *
     * <p>The method first converts each image into an embedding. It then
     * calculates the square root of the sum of the squared differences
     * between corresponding embedding values.
     *
     * @param image1 the normalized pixel values of the first fingerprint
     * @param image2 the normalized pixel values of the second fingerprint
     * @return the Euclidean distance between the two embeddings
     * @throws TranslateException if either image cannot be processed
     * @throws IllegalArgumentException if either image has an invalid size
     * @throws IllegalStateException if the embedding dimensions differ
     */
    public float distance(float[] image1, float[] image2) throws TranslateException {
        float[] a = embed(image1);
        float[] b = embed(image2);

        if (a.length != b.length) {
            throw new IllegalStateException("Embedding dimensions do not match.");
        }

        // Accumulate squared diffs between corresponding embedding
        // values using double precision for the sum.
        double sum = 0.0;
        for (int i = 0; i < a.length; i++) {
            double difference = a[i] - b[i];
            sum += difference * difference;
        }

        return (float) Math.sqrt(sum);
    }

    /**
     * Determines whether two fingerprint images meet the configured
     * embedding-distance threshold for a match.
     *
     * @param image1 the normalized pixel values of the first fingerprint
     * @param image2 the normalized pixel values of the second fingerprint
     * @return {@code true} if the distance is at or below the threshold,
     * {@code false} otherwise
     * @throws TranslateException if either image cannot be processed
     * @throws IllegalArgumentException if either image has an invalid size
     */
    public boolean isGenuineMatch(float[] image1, float[] image2)
            throws TranslateException {
        return distance(image1, image2) <= THRESHOLD;
    }

    /**
     * Calculates the Euclidean distance between two precomputed fingerprint
     * embeddings without running model inference.
     *
     * @param embedding1 the first fingerprint embedding
     * @param embedding2 the second fingerprint embedding
     * @return the Euclidean distance between the embeddings
     * @throws IllegalArgumentException if either embedding is empty
     * @throws IllegalStateException if the embedding dimensions differ
     */
    public float embeddingDistance(float[] embedding1, float[] embedding2) {
        if (embedding1.length == 0 || embedding2.length == 0) {
            throw new IllegalArgumentException(
                    "Embeddings must not be empty."
            );
        }

        if (embedding1.length != embedding2.length) {
            throw new IllegalStateException(
                    "Embedding dimensions do not match."
            );
        }

        double sum = 0.0;

        for (int i = 0; i < embedding1.length; i++) {
            double difference = embedding1[i] - embedding2[i];
            sum += difference * difference;
        }

        return (float) Math.sqrt(sum);
    }

    /**
     * Determines whether a precomputed embedding distance meets the
     * configured genuine-match threshold.
     *
     * @param distance the Euclidean distance between two embeddings
     * @return true if the distance is at or below the threshold
     */
    public boolean isGenuineMatch(float distance) {
        return distance <= THRESHOLD;
    }

    /**
     * Releases the resources used by the predictor, model, and manager.
     */
    @Override
    public void close() {
        predictor.close();
        model.close();
        manager.close();
    }
}
